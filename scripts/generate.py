def generate(config, stats, out, static=False):
    transcripts = {}
    outputs = []
    # Build every image before changing any output file: bad config cannot leave a partial scene set.
    for compact in (False,True):
        for theme in ('dark','light'):
            scenes = build_scenes(config, stats, compact, theme, static)
            for name,canvas in scenes.items():
                suffix = '-compact' if compact else ''
                outputs.append((out/'profile'/f'{name}{suffix}-{theme}.svg',canvas.render()))
                if not compact and theme=='dark':
                    transcripts[name] = transcript(canvas)
            suffix = '-compact' if compact else ''
            still=session(config,stats,theme,compact,True)
            outputs.append((out/'profile'/f'session{suffix}-still-{theme}.svg',still.render()))
            for style in STYLES:
                canvas=toolbox(config,stats,theme,compact,static,style=style)
                suffix='-compact' if compact else ''
                outputs.append((out/'previews/toolbox'/f'{style}{suffix}-{theme}.svg',canvas.render()))
    for path, content in outputs:
        write(path,content)
    write(out/'README.md',readme())
    write(out/'previews'/'index.html',preview())
    write(out/'previews'/'toolbox-variants.html',comparison_preview())
    for name, text in transcripts.items():
        write(out/'previews'/'text'/f'{name}.txt',text+'\n')
    print(f'Generated {len(outputs)} SVGs, README and local preview in {out}')
    print(f'Data: {stats["source"]}; fetched {stats["fetched_at"]}')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--config',type=Path,default=ROOT/'config.toml')
    parser.add_argument('--snapshot',type=Path,help='Override the configured public data snapshot')
    parser.add_argument('--out',type=Path,default=ROOT)
    parser.add_argument('--refresh',action='store_true',help='Fetch real public GitHub data before generating')
    parser.add_argument('--static',action='store_true',help='Emit the complete static states without motion')
    args = parser.parse_args(argv)
    with args.config.open('rb') as source:
        config = tomllib.load(source)
    snapshot = args.snapshot or args.config.resolve().parent/config['github']['snapshot']
    if args.refresh:
        stats = github_stats.fetch(config['profile']['github'],config['github']['exclude_repos'])
        github_stats.save_snapshot(snapshot,stats)
    else:
        stats = github_stats.load_snapshot(snapshot,config['profile']['github'])
    generate(config,stats,args.out.resolve(),args.static)


if __name__=='__main__':
    try:
        main()
    except (ValueError,OSError,RuntimeError) as error:
        print(f'profile: {error}',file=sys.stderr)
        sys.exit(1)
